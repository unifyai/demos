# ---------------------------------------------------------------- formatting
def a(cond, arm):
    return C[cond]["arms"][arm]


def d(cond, pair, key):
    return C[cond]["compare"][pair][key]


def pct(x, n=True):
    if not x or not x.get("n"):
        return "-"
    s = f"{100 * x['p']:.0f}% [{100 * max(0.0, x['lo']):.0f}, {100 * x['hi']:.0f}]"
    return s + (f" ({x['k']}/{x['n']})" if n else "")


def p0(x):
    return f"{100 * x['p']:.0f}%"


def num(x, nd=2, unit=""):
    if not x or x.get("mean") is None or (isinstance(x["mean"], float) and math.isnan(x["mean"])):
        return "-"
    return f"{x['mean']:.{nd}f}{unit} [{x['lo']:.{nd}f}, {x['hi']:.{nd}f}]"


def m(x, nd=2):
    return f"{x['mean']:.{nd}f}"


def dd(x, scale=1.0, nd=1, unit=""):
    if not x or x.get("diff") is None:
        return "-"
    return f"{scale * x['diff']:+.{nd}f}{unit} [{scale * x['lo']:+.{nd}f}, {scale * x['hi']:+.{nd}f}]"


def s(x, nd=2):
    return f"{x:.{nd}f} s"


def usd(x, nd=3):
    return f"${x:.{nd}f}"


def p90(x):
    return f"{x:.1f}" if x is not None else "-"


# ---------------------------------------------------------------- tables
def arm_table(cond, arms=ARMS, label=None):
    out = ["| Arm | Correct answers | Calls with a wrong or invented fact | Withdrawn answers said anyway | Naturalness (judge, 1-5) | "
           "Double replies per call | First word, median (p90) | Turns waiting > 2 s | Answer time, median | Cost per call |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for arm in arms:
        if arm not in C[cond]["arms"]:
            continue
        x = a(cond, arm)
        name = f"`{arm}`" + (f" {label[arm]}" if label and arm in label else "")
        out.append(f"| {name} | {pct(x['correct'])} | {pct(x['wrong_any'], False)} | {pct(x['stale'])} | {num(x['naturalness'])} | "
                   f"{num(x['judge_double_per_call'])} | {s(x['ttfw_median'])} ({p90(x['ttfw_p90'])}) | {pct(x['slow_turns'], False)} | "
                   f"{num(x['t_answer_median'], 1, ' s')} | {usd(x['cost_per_call']['mean'])} |")
    return "\n".join(out)


def diff_table(cond, pairs):
    out = ["| Difference (first arm minus second) | Correct (points) | Calls with a wrong or invented fact (points) | Withdrawn answers said (points) | "
           "Naturalness | Double replies per call | First word, median (s) | Turns waiting > 2 s (points) | Answer time (s) | Cost per call ($) |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for k in pairs:
        if k not in C[cond]["compare"]:
            continue
        x = C[cond]["compare"][k]
        out.append(f"| {k.replace(' - ', ' minus ')} | {dd(x['correct'], 100)} | {dd(x['wrong_any'], 100)} | {dd(x['stale'], 100)} | "
                   f"{dd(x['nat'], 1, 2)} | {dd(x['double'], 1, 2)} | {dd(x['ttfw'], 1, 2)} | {dd(x['slow_turns'], 100)} | "
                   f"{dd(x['t_answer'], 1, 1)} | {dd(x['cost'], 1, 3)} |")
    return "\n".join(out)


def tiers_table():
    rows = [("cheap: Haiku 5.5", CHEAP_A), ("mid: Sonnet 5.5 (low)", MID), ("top: Opus 5.5 (high)", TOP)]
    out = ["| Slow model (fast: Haiku 5.5) | Arm | Calls | Correct answers | Withdrawn answers said anyway | Naturalness | "
           "Double replies per call | First word on requests, median | Answer time, median | Cost per call |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for tier, cond in rows:
        for arm in ["relay", "slow_speaks", "slow_only"]:
            x = a(cond, arm)
            note = " (= `fast_only`)" if cond == CHEAP_A and arm == "slow_only" else ""
            out.append(f"| {tier} | `{arm}`{note} | {x['calls']} | {pct(x['correct'])} | {pct(x['stale'], False)} | {num(x['naturalness'])} | "
                       f"{num(x['judge_double_per_call'])} | {s(x['ttfw_requests_median']['mean'])} | {m(x['t_answer_median'], 1)} s | "
                       f"{usd(x['cost_per_call']['mean'])} |")
    for arm in ["fast_only", "fast_only_think", "fast_context", "fast_context_think"]:
        x = a(MID, arm)
        out.append(f"| (no slow model) | `{arm}` | {x['calls']} | {pct(x['correct'])} | {pct(x['stale'], False)} | {num(x['naturalness'])} | "
                   f"{num(x['judge_double_per_call'])} | {s(x['ttfw_requests_median']['mean'])} | {m(x['t_answer_median'], 1)} s | "
                   f"{usd(x['cost_per_call']['mean'])} |")
    return "\n".join(out)


def delay_table():
    out = ["| Arm | Slow-model delay D | Correct answers | Withdrawn answers said anyway | Naturalness | Double replies per call | "
           "First word on requests, median | Turns with no reply before Sam goes on | Answer time, median |",
           "|---|---|---|---|---|---|---|---|---|"]
    for arm in ["relay", "slow_speaks", "slow_only", "slow_filler"]:
        for dl, cond in [(0, MID), (8, D8)]:
            x = a(cond, arm)
            out.append(f"| `{arm}` | {dl} s | {pct(x['correct'])} | {pct(x['stale'], False)} | {num(x['naturalness'])} | "
                       f"{num(x['judge_double_per_call'])} | {s(x['ttfw_requests_median']['mean'])} | {pct(x['no_reply'], False)} | "
                       f"{m(x['t_answer_median'], 1)} s |")
    return "\n".join(out)


FAST = ["fast_only", "fast_only_think", "fast_context", "fast_context_think"]


def verdict_table():
    out = ["| Condition | Design | (a) answers sooner | (b) as correct, no more invented | (c) as natural, not more doubles | "
           "**Holds against `slow_only`** | Ahead of (correct or fewer invented, interval excluding 0) | Holds if the first-word median counts only answered turns |",
           "|---|---|---|---|---|---|---|---|"]
    yn = {True: "yes", False: "no"}
    for cond, label in COND_NAMES.items():
        for sd in ["relay", "slow_speaks"]:
            v = C[cond]["verdict"].get(sd)
            if not v:
                continue
            ahead = [f"`{f}`" for f in FAST if v["ahead_of_fast"].get(f)]
            behind = [f for f in FAST if f in v["ahead_of_fast"]]
            ahead_s = (", ".join(ahead) if ahead else "none") if behind else "(no single-fast arm run)"
            out.append(f"| {label} | `{sd}` | {yn[v['a_responsive']]} | {yn[v['b_correct']]} | {yn[v['c_natural']]} | "
                       f"**{yn[v['holds']]}** | {ahead_s} | {yn[v['holds_with_answered_only_median']]} |")
    return "\n".join(out)


def judge_table():
    j = R["judge_validation"]
    out = ["| Label | Calls the hand labels flag | Calls the judge flags | Both | Agreement | Cohen's kappa |", "|---|---|---|---|---|---|"]
    names = {"double_replies": "Double replies", "contradictions": "Contradictions", "stale": "Withdrawn answers said",
             "wrong_or_invented": "Wrong or invented facts"}
    for k, label in names.items():
        e = j["events"][k]
        out.append(f"| {label} | {e['hand_any']} | {e['judge_any']} | {e['both']} | {100 * e['agree']:.0f}% | {e['kappa']:.2f} |")
    return "\n".join(out)


def cost_table():
    c = R["cost"]
    out = ["| Spend | Cost |", "|---|---|"]
    order = ["mid tier", "cheap tier", "top tier", "judge"]
    for k in order + [k for k in c["today_by_group"] if k not in order]:
        if k in c["today_by_group"]:
            out.append(f"| Today's models: {k} | ${c['today_by_group'][k]:.2f} |")
    out.append(f"| **Today's models, in all** | **${c['today_models']:.2f}** |")
    out.append(f"| Era models of Plan amendment 3 (set aside, not analysed; outside today's budget) | ${c['era_models']:.2f} |")
    out.append(f"| Both ledgers, in all | ${c['total']:.2f} |")
    return "\n".join(out)


