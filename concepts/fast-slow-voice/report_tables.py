def judge_per_call() -> float:
    j = next(v for k, v in R["cost"]["by_tag_model"].items() if k.startswith("fast-slow-voice/judge |"))
    return j["cost"] / j["calls"]


def per_call(cond, arms) -> float:
    return sum(a(cond, x)["cost_per_call"]["mean"] for x in arms)


def not_run_table() -> str:
    jc = judge_per_call()
    slow3 = ["relay", "slow_speaks", "slow_only"]
    rows = [
        ("Top tier, seeds 1 and 2 (3 arms x 16 scripts x 2)", 32 * per_call(TOP, slow3) + 96 * jc, "from the top tier"),
        ("Delay D = 4 s, mid tier (4 slow arms x 16 x 3)", 48 * per_call(D8, ["relay", "slow_speaks", "slow_only", "slow_filler"]) + 192 * jc,
         "from D = 8"),
        ("`medium` size, mid tier (8 arms x 16 x 1)", 16 * (per_call(SMALL, ARMS) + per_call(MID, ARMS)) / 2 + 128 * jc,
         "midway between `small` and `realistic`"),
        ("Mid tier on OpenAI, GPT-6.1 Sol as the slow model (3 slow arms x 16 x 3)", 48 * per_call(MID, slow3) + 144 * jc,
         "Sonnet 5.5's cost per call (the same list prices); a guess"),
        ("Sonnet 5.5 at effort high (3 slow arms x 16 x 1)", 16 * per_call(MID, slow3) + 48 * jc,
         "Sonnet 5.5 at effort low; a lower bound"),
    ]
    out = ["| Not run | Estimated cost | Estimated from |", "|---|---|---|"]
    for name, cost, how in rows:
        out.append(f"| {name} | ${cost:.2f} | {how} |")
    out.append(f"| **All of the above** | **${sum(r[1] for r in rows):.2f}** | |")
    return "\n".join(out)


